export type TranslationKey = keyof typeof en;
export type Translate = (key: TranslationKey, replacements?: Record<string, string | number>) => string;
export function translator(language: Language): Translate {
  const dictionary = language === 'zh-CN' ? zh : en;
  return (key, replacements) => {
    let value = dictionary[key];
    for (const [name, replacement] of Object.entries(replacements ?? {})) value = value.replaceAll(`{${name}}`, String(replacement));
    return value;
  };
}
